#include "../../includes/minishell.h"

int	bi_pwd(void)
{
	char	*cwd;

	cwd = getcwd(NULL, 0);
	if (!cwd)
		return (print_error("pwd", NULL, strerror(errno)));
	ft_putendl_fd(cwd, 1);
	free(cwd);
	return (0);
}
